"""Build the X0 reference table from raw outputs and independent oracles.

    python -m uv run --locked python tools/x0_table.py --raw docs/verification/X0_raw.json \
        (--write docs/verification/X0.md | --check docs/verification/X0.md)

Oracles never call argus: exact fractions and rational path sums, Taylor series
in Fraction for exp(-x), and scipy.linalg.expm for matrix exponentials. The
generated block between the X0-TABLE markers is replaced (--write) or compared
(--check, exit 1 on difference). Exits 2 when any case misses its tolerance.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from fractions import Fraction
from itertools import product
from pathlib import Path
from typing import Any

import numpy as np
from scipy.linalg import expm

BEGIN = "<!-- X0-TABLE:BEGIN (generated by tools/x0_table.py; do not edit) -->"
END = "<!-- X0-TABLE:END -->"


def exp_neg(x: Fraction, terms: int = 80) -> Fraction:
    """exp(-x) as a Taylor sum; truncation error < 1e-40 for 0 <= x <= 2."""
    total, term = Fraction(0), Fraction(1)
    for n in range(terms):
        total += term
        term *= -x / (n + 1)
    return total


def rational_shared_bias(p: Fraction, rho: Fraction, q: Fraction, ys: Sequence[int]) -> Fraction:
    def likelihood(z: int) -> Fraction:
        total = Fraction(0)
        for g, weight in ((0, 1 - rho), (1, rho)):
            for y in ys:
                weight *= (1 - q) if y == (z ^ g) else q
            total += weight
        return total

    return p * likelihood(1) / (p * likelihood(1) + (1 - p) * likelihood(0))


def rational_static_joint(
    prior: Sequence[Fraction], q: Fraction, ys: Sequence[int]
) -> list[Fraction]:
    weights = []
    for state, weight in enumerate(prior):
        z, g = divmod(state, 2)
        for y in ys:
            weight *= (1 - q) if y == (z ^ g) else q
        weights.append(weight)
    total = sum(weights)
    return [w / total for w in weights]


def path_enumeration(case: dict[str, Any]) -> np.ndarray:
    def gen(r01: float, r10: float) -> np.ndarray:
        return np.array([[-r01, r01], [r10, -r10]])

    pz = expm(gen(*case["rates_z"]) * case["gap_seconds"])
    pg = expm(gen(*case["rates_g"]) * case["gap_seconds"])
    ys, q, prior = case["observations"], case["q"], case["prior"]
    mass = np.zeros(4)
    for path in product(range(4), repeat=len(ys)):
        weight = prior[path[0]]
        for k, state in enumerate(path):
            z, g = divmod(state, 2)
            if k:
                zp, gp = divmod(path[k - 1], 2)
                weight *= pz[zp, z] * pg[gp, g]
            weight *= (1 - q) if ys[k] == (z ^ g) else q
        mass[path[-1]] += weight
    return mass / mass.sum()


def dec(value: float) -> Fraction:
    """The intended decimal parameter, e.g. 0.2 -> 1/5."""
    return Fraction(repr(value))


Check = tuple[Any, str, float, str]  # oracle value, method, deviation, tolerance text


def scalar(output: float, oracle: Fraction, method: str, atol: float) -> tuple[Check, bool]:
    deviation = abs(Fraction(output) - oracle)
    return (float(oracle), method, float(deviation), f"abs {atol:g}"), deviation <= atol


def evaluate(case: dict[str, Any]) -> tuple[Check, bool]:
    i, out = case["inputs"], case["output"]
    cid = case["id"]
    if cid in ("M1-01", "M1-02", "M1-03", "M1-04"):
        r01, r10, p, dt = dec(i["rate_01"]), dec(i["rate_10"]), dec(i["p"]), dec(i["dt_seconds"])
        k = r01 + r10
        if k == 0:
            # Identity means the very same double, so the oracle is the input bit pattern.
            return scalar(out, Fraction(i["p"]), "identity of the input double (k=0)", 0.0)
        pi = r01 / k
        if k * dt > 2:
            # e^{-500} < 1e-200: the stationary value is exact far beyond double precision.
            return scalar(out, pi, "stationary pi, remainder < 1e-200", 1e-14)
        oracle = pi + (p - pi) * exp_neg(k * dt)
        if cid == "M1-04":
            deviation = abs(Fraction(out) - oracle) / oracle
            ok = deviation <= Fraction(1, 10**9)
            return (float(oracle), "Taylor exp(-x) in Fraction", float(deviation), "rel 1e-09"), ok
        return scalar(out, oracle, "Taylor exp(-x) in Fraction", 1e-14)
    if cid == "M1-05":
        expected = expm(
            np.array([[-i["rate_01"], i["rate_01"]], [i["rate_10"], -i["rate_10"]]])
            * i["dt_seconds"]
        )
        deviation = float(np.max(np.abs(np.array(out) - expected)))
        return (expected.round(15).tolist(), "scipy.linalg.expm", deviation, "abs 1e-12"), (
            deviation <= 1e-12
        )
    if cid in ("M2-01", "M2-02", "M2-03"):
        oracle = rational_shared_bias(
            dec(i["prior_open"]), dec(i["rho"]), dec(i["q"]), i["observations"]
        )
        check, ok = scalar(out, oracle, f"rational sum over g = {oracle}", 1e-14)
        return check, ok
    if cid == "M2-04":
        e = dec(i["error"])
        oracle = (1 - e) ** 2 / ((1 - e) ** 2 + e**2)
        check, ok = scalar(out, oracle, f"naive formula = {oracle}; true model 325/362", 1e-14)
        return check, ok and out > 325 / 362
    if cid == "M2-05":
        ok = isinstance(out, str) and out.startswith("ImpossibleEvidence")
        return ("ImpossibleEvidence", "zero marginal likelihood", 0.0, "exception"), ok
    if cid == "M3-01":
        expected = path_enumeration(i)
        deviation = float(np.max(np.abs(np.array(out) - expected)))
        return (expected.round(15).tolist(), "4^3 path sum, scipy expm", deviation, "abs 1e-12"), (
            deviation <= 1e-12
        )
    if cid == "M3-02":
        exact = rational_static_joint([dec(v) for v in i["prior"]], dec(i["q"]), i["observations"])
        deviation = max(abs(Fraction(o) - x) for o, x in zip(out, exact, strict=True))
        open_mass = exact[2] + exact[3]
        method = f"rational joint, P(z=1) = {open_mass}"
        return ([float(x) for x in exact], method, float(deviation), "abs 1e-14"), (
            deviation <= Fraction(1, 10**14)
        )
    raise ValueError(f"no oracle for case {cid}")


def fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.17g}"
    if isinstance(value, list):
        flat = np.array(value, dtype=float).ravel()
        return "[" + ", ".join(f"{v:.15g}" for v in flat) + "]"
    return str(value)


def table(raw: dict[str, Any]) -> tuple[str, bool]:
    rows = [
        BEGIN,
        "",
        f"Rohdaten: `docs/verification/X0_raw.json` (Schema {raw['schema_version']}, "
        f"argus {raw['argus_version']}).",
        "",
        "| ID | Modell | Art | Fall | Implementierung | Oracle | Oracle-Methode | Abweichung "
        "| Toleranz | Ergebnis |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    all_ok = True
    for case in raw["cases"]:
        (oracle, method, deviation, tolerance), ok = evaluate(case)
        all_ok &= ok
        rows.append(
            f"| {case['id']} | {case['model']} | {case['kind']} | {case['description']} "
            f"| {fmt(case['output'])} | {fmt(oracle)} | {method} | {deviation:.3g} "
            f"| {tolerance} | {'PASS' if ok else 'FAIL'} |"
        )
    rows += ["", END]
    return "\n".join(rows), all_ok


def splice(document: str, block: str) -> str:
    head, rest = document.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", type=Path)
    mode.add_argument("--check", type=Path)
    args = parser.parse_args()
    raw = json.loads(args.raw.read_text(encoding="utf-8"))
    block, all_ok = table(raw)
    target: Path = args.write or args.check
    document = target.read_text(encoding="utf-8")
    updated = splice(document, block)
    if args.write:
        target.write_bytes(updated.encode("utf-8"))
        print(f"wrote table for {len(raw['cases'])} cases into {target}")
    elif updated != document:
        print("STALE: X0 table differs from raw outputs")
        return 1
    else:
        print(f"PASS: X0 table matches raw outputs ({len(raw['cases'])} cases)")
    if not all_ok:
        print("FAIL: at least one case misses its tolerance")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
